# 9: Core Provider-Neutrality Guard (Static AST/Content Invariant Check)
# ==============================================================================

def test_core_provider_neutrality_guard_no_hardcoded_vendor_strings():
    """
    DAIO-PORTABILITY-INVARIANT-001 Guard:
    Scans DAIO Core modules (orchestrator, store, worker, watchdog, router, models)
    using Python AST parsing to ensure vendor strings (chatgpt, openai, claude,
    anthropic, antigravity, gemini, codex) do not appear in executable logic.
    """
    import ast

    core_dir = Path(__file__).resolve().parent.parent / "scripts" / "daio_closed_loop"
    core_modules = [
        "orchestrator.py",
        "store.py",
        "worker.py",
        "watchdog.py",
        "router.py",
        "models.py",
    ]

    guarded_tokens = {"chatgpt", "openai", "claude", "anthropic", "antigravity", "gemini", "codex"}

    violations = []
    for mod_name in core_modules:
        file_path = core_dir / mod_name
        if not file_path.exists():
            continue

        tree = ast.parse(file_path.read_text(encoding="utf-8"), filename=str(file_path))

        # Collect all docstring Constant nodes to ignore
        docstring_nodes = set()
        for parent in ast.walk(tree):
            if isinstance(parent, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                if parent.body and isinstance(parent.body[0], ast.Expr) and isinstance(parent.body[0].value, ast.Constant):
                    docstring_nodes.add(parent.body[0].value)

        # Check all string constants in executable AST nodes
        for node in ast.walk(tree):
            if node in docstring_nodes:
                continue

            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                val_lower = node.value.lower()
                for token in guarded_tokens:
                    if re.search(r'\b' + re.escape(token) + r'\b', val_lower):
                        violations.append(f"{mod_name}:{getattr(node, 'lineno', '?')} -> Constant('{node.value}')")

    assert len(violations) == 0, f"Provider-neutrality executable violations found in DAIO Core:\n" + "\n".join(violations)


