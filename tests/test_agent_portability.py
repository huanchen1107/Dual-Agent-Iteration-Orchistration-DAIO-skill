class MockPortabilityAgentAdapter(AgentAdapter):
    """Generic mock adapter implementing the canonical AgentAdapter interface."""

    def __init__(
        self,
        provider_name: str,
        role: AgentRole,
        capabilities: Set[AgentCapability],
        canned_response: Optional[AgentResponse] = None,
        health_status: AgentHealthStatus = AgentHealthStatus.READY,
    ) -> None:
        self.provider_name = provider_name
        self.role = role
        self.capabilities = capabilities
        self.canned_response = canned_response
        self.health_status = health_status
        self.executed_requests: List[AgentRequest] = []

    def get_identity(self) -> AgentIdentity:
        return AgentIdentity(
            logical_role=self.role,
            provider=self.provider_name,
            adapter_type="mock_adapter",
            model=f"{self.provider_name}-v1",
            instance_id=f"{self.provider_name}-{self.role.value.lower()}",
        )

    def get_capabilities(self) -> Set[AgentCapability]:
        return set(self.capabilities)

    def check_health(self) -> AgentHealth:
        return AgentHealth(
            status=self.health_status,
            provider_reachable=(self.health_status in (AgentHealthStatus.READY, AgentHealthStatus.DEGRADED)),
            credentials_available=True,
            capabilities_available=list(self.capabilities),
        )

    async def execute(self, request: AgentRequest) -> AgentResponse:
        self.executed_requests.append(request)
        if self.canned_response:
            return self.canned_response

        # Default normalized response
        return AgentResponse(
            request_id=request.request_id,
            agent_identity=self.get_identity(),
            status="SUCCESS",
            summary=f"Processed by {self.provider_name}",
            proposed_edits=[
                ProposedFileEdit(file_path="src/main.py", new_content=f"# generated by {self.provider_name}\n")
            ],
            evidence=[
                AgentEvidence(evidence_type="MOCK_EXECUTION", uri="evidence/run.log", description=f"Executed on {self.provider_name}")
            ],
        )


