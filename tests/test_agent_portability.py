def test_adapter_registry_fallback_cascade():
    registry = AgentAdapterRegistry()

    # Primary adapter is UNAVAILABLE
    primary_adapter = MockPortabilityAgentAdapter(
        provider_name="primary_failing_provider",
        role=AgentRole.ENGINEERING_EXECUTION,
        capabilities={AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY},
        health_status=AgentHealthStatus.UNAVAILABLE,
    )
    # Secondary adapter is READY
    fallback_adapter = MockPortabilityAgentAdapter(
        provider_name="healthy_fallback_provider",
        role=AgentRole.ENGINEERING_EXECUTION,
        capabilities={AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY},
        health_status=AgentHealthStatus.READY,
    )

    registry.register(primary_adapter, priority=10)
    registry.register(fallback_adapter, priority=20)

    resolved = registry.resolve(
        role=AgentRole.ENGINEERING_EXECUTION,
        required_capabilities={AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY},
    )

    assert resolved is not None
    assert resolved.get_identity().provider == "healthy_fallback_provider"


