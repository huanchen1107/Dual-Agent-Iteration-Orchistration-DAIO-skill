def test_canonical_agent_request_and_response_normalization():
    adapter_a = MockPortabilityAgentAdapter(
        provider_name="vendor_alpha",
        role=AgentRole.ENGINEERING_EXECUTION,
        capabilities={AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY, AgentCapability.RUN_TESTS},
    )
    adapter_b = MockPortabilityAgentAdapter(
        provider_name="vendor_beta",
        role=AgentRole.ENGINEERING_EXECUTION,
        capabilities={AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY, AgentCapability.RUN_TESTS},
    )

    request = AgentRequest(
        request_id="req-test-001",
        work_id="work-101",
        change_id="CHANGE_101",
        role=AgentRole.ENGINEERING_EXECUTION,
        requested_capabilities=[AgentCapability.READ_REPOSITORY, AgentCapability.WRITE_REPOSITORY],
        instruction="Refactor auth service",
        project_root="/tmp/project",
        allowed_scope=["src/**"],
    )

    resp_a = asyncio.run(adapter_a.execute(request))
    resp_b = asyncio.run(adapter_b.execute(request))

    assert resp_a.contract_version == "daio-agent/v1"
    assert resp_b.contract_version == "daio-agent/v1"
    assert resp_a.status == "SUCCESS"
    assert resp_b.status == "SUCCESS"
    assert resp_a.agent_identity.provider == "vendor_alpha"
    assert resp_b.agent_identity.provider == "vendor_beta"
    assert len(resp_a.proposed_edits) == 1
    assert len(resp_b.proposed_edits) == 1


